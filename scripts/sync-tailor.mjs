#!/usr/bin/env node
/**
 * Single-sources Tailor Today's shared files from the client sources of truth
 * into the tailor-devotional edge function:
 *
 *   src/data/tailorBank.ts   -> supabase/functions/tailor-devotional/tailorBank.ts   (verbatim)
 *   src/lib/tailorAccess.ts  -> supabase/functions/tailor-devotional/tailorAccess.ts (verbatim)
 *   src/data/quotes.ts       -> supabase/functions/tailor-devotional/quotes.ts      (transformed)
 *
 * The quotes dataset rides along so Tailor Today's tradition quote is selected
 * from the app's OWN daily-quotes shelf — never a newly authored line. The
 * client file imports its Audience type from '@/types', which the edge
 * runtime cannot resolve, so the transform swaps that one import for a local
 * two-value type and renames the parameter types to match. The DATA — every
 * quote, both tracks — is carried byte-for-byte; a test pins the two datasets
 * equal so the transform can never quietly edit a quote.
 *
 * The bank and the entitlement seam must be identical on both sides of the
 * wire: the client shows the bank's labels and asks the seam whether to offer
 * the door; the server selects from the bank and asks the same seam whether
 * to build. A drifted copy would mean the app offers what the server refuses,
 * or the server reads a bank the app never approved. Never edit the generated
 * files directly — edit the client sources and re-run:
 *
 *   npm run sync:tailor     regenerate
 *   npm run check:tailor    fail if a generated file is stale (also covered by tests)
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const checkOnly = process.argv.includes('--check');

/**
 * The quotes transform: the client dataset, with its one client-only import
 * replaced by a local type. Fails loudly if the source stops matching the
 * shapes it knows how to carry — a silent half-transform would be worse than
 * none.
 */
function transformQuotes(src) {
  const importLine = "import type { Audience } from '@/types';\n";
  if (!src.includes(importLine)) throw new Error('quotes transform: Audience import line not found');
  let out = src.replace(importLine, "export type QuoteAudience = 'men' | 'women';\n");
  out = out.split('(audience: Audience)').join('(audience: QuoteAudience)');
  out = out.split('audience: Audience').join('audience: QuoteAudience');
  // After the rename, the only remaining bare 'Audience' may be inside
  // 'QuoteAudience' itself.
  const stripped = out.split('QuoteAudience').join('');
  if (/\bAudience\b/.test(stripped)) throw new Error('quotes transform: unhandled Audience reference remains');
  return out;
}

const MAPPINGS = [
  {
    source: 'src/data/tailorBank.ts',
    target: 'supabase/functions/tailor-devotional/tailorBank.ts',
    note: 'the passage and song banks',
  },
  {
    source: 'src/lib/tailorAccess.ts',
    target: 'supabase/functions/tailor-devotional/tailorAccess.ts',
    note: 'the entitlement seam',
  },
  {
    source: 'src/data/quotes.ts',
    target: 'supabase/functions/tailor-devotional/quotes.ts',
    note: 'the daily-quotes dataset',
    transform: transformQuotes,
  },
];

let drift = false;
for (const { source, target, note, transform } of MAPPINGS) {
  const header = `// GENERATED by scripts/sync-tailor.mjs from ${source} — do not edit by hand.\n// Single-sourced so client and server share ${note} exactly.\n`;
  const raw = readFileSync(join(root, source), 'utf8');
  const generated = header + (transform ? transform(raw) : raw);
  const full = join(root, target);
  const current = existsSync(full) ? readFileSync(full, 'utf8') : null;
  if (current !== generated) {
    drift = true;
    if (checkOnly) {
      console.error(`DRIFT: ${target} is stale. Run: npm run sync:tailor`);
    } else {
      mkdirSync(dirname(full), { recursive: true });
      writeFileSync(full, generated);
      console.log(`synced ${target}`);
    }
  } else if (!checkOnly) {
    console.log(`already in sync: ${target}`);
  }
}
if (checkOnly && drift) process.exit(1);
if (checkOnly) console.log('tailor shared files in sync.');
