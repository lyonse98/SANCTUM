/*
# Put the Gospel email list behind server-side functions

## Why this migration exists

The first version of this table let the app talk to it directly over the REST API.
That had two problems:

1. A bug: the read policy was `active = true`. When the app tried to set `active = false`
   (unsubscribe), the updated row no longer matched the read policy, so Postgres rejected
   the whole update. Unsubscribing was impossible.
2. A privacy leak: the app key is embedded in the website's JavaScript, so it is public.
   Anyone could have used it to download every subscriber's email address. For an app whose
   whole promise is privacy, that is not acceptable — a list of men who signed up for a
   Catholic companion app is sensitive on its own.

## What changes

### 1. The table is no longer reachable from the browser at all
All direct privileges are revoked from `anon` and `authenticated`, and all four policies are
replaced with deny-all. Reading or writing the table directly now fails for both roles.

### 2. Three server-side functions become the only way in
These run with the table owner's rights, so they work even though the browser cannot touch
the table. Each one validates its own input, because anyone can call them.

- `subscribe_email_reminder(p_email, p_hour)` — checks the address is a plausible email and
  the hour is 0-23, then adds or re-activates the row. Returns a secret token.
- `unsubscribe_email_reminder(p_token)` — marks the row inactive. Needs the secret token.
- `set_email_reminder_hour(p_token, p_hour)` — changes the send time. Needs the secret token.

The token is 48 hex characters, generated by the database, and is never readable through any
read path. The browser stores it locally after subscribing, which is what lets a man stop the
emails later without an account.

### 3. Existing rows
Untouched. Any address already collected keeps its `send_hour` and its token.

## Security notes

- `SECURITY DEFINER` with `SET search_path = ''`: every object is schema-qualified, so the
  functions cannot be hijacked by a rogue object placed earlier in the search path.
- `EXECUTE` is revoked from `PUBLIC` first, then granted only to `anon` and `authenticated`.
- The functions never return an address or a token except the one just created or matched.
- No table grants means no way to enumerate the list, which is the point.

## Known limitation

Subscribing with an address that is already on the list returns that address's existing
token. Someone who knows another man's address could therefore stop his emails. With no
sign-in there is no way to distinguish the owner of an address from a stranger. The fix,
when it matters, is a confirmation email before the subscription becomes active.
*/

REVOKE ALL ON TABLE public.email_reminder_subscribers FROM anon, authenticated;

DROP POLICY IF EXISTS anon_select_active_email_subscribers ON public.email_reminder_subscribers;
DROP POLICY IF EXISTS anon_insert_email_subscribers ON public.email_reminder_subscribers;
DROP POLICY IF EXISTS anon_update_email_subscribers ON public.email_reminder_subscribers;
DROP POLICY IF EXISTS anon_delete_email_subscribers ON public.email_reminder_subscribers;

DROP POLICY IF EXISTS deny_select_email_subscribers ON public.email_reminder_subscribers;
CREATE POLICY deny_select_email_subscribers ON public.email_reminder_subscribers
  FOR SELECT TO anon, authenticated USING (false);

DROP POLICY IF EXISTS deny_insert_email_subscribers ON public.email_reminder_subscribers;
CREATE POLICY deny_insert_email_subscribers ON public.email_reminder_subscribers
  FOR INSERT TO anon, authenticated WITH CHECK (false);

DROP POLICY IF EXISTS deny_update_email_subscribers ON public.email_reminder_subscribers;
CREATE POLICY deny_update_email_subscribers ON public.email_reminder_subscribers
  FOR UPDATE TO anon, authenticated USING (false) WITH CHECK (false);

DROP POLICY IF EXISTS deny_delete_email_subscribers ON public.email_reminder_subscribers;
CREATE POLICY deny_delete_email_subscribers ON public.email_reminder_subscribers
  FOR DELETE TO anon, authenticated USING (false);

CREATE OR REPLACE FUNCTION public.subscribe_email_reminder(p_email text, p_hour integer)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $fn$
DECLARE
  v_email text := lower(btrim(coalesce(p_email, '')));
  v_token text;
BEGIN
  IF v_email !~ '^[^\s@]+@[^\s@]+\.[^\s@]+$' OR length(v_email) > 254 THEN
    RAISE EXCEPTION 'invalid_email' USING ERRCODE = '22023';
  END IF;

  IF p_hour IS NULL OR p_hour < 0 OR p_hour > 23 THEN
    RAISE EXCEPTION 'invalid_hour' USING ERRCODE = '22023';
  END IF;

  INSERT INTO public.email_reminder_subscribers (email, send_hour)
  VALUES (v_email, p_hour)
  ON CONFLICT (email) DO UPDATE
    SET active = true,
        send_hour = EXCLUDED.send_hour,
        updated_at = now()
  RETURNING unsubscribe_token INTO v_token;

  RETURN v_token;
END;
$fn$;

CREATE OR REPLACE FUNCTION public.unsubscribe_email_reminder(p_token text)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $fn$
DECLARE
  v_rows integer;
BEGIN
  IF p_token IS NULL OR length(p_token) <> 48 THEN
    RETURN false;
  END IF;

  UPDATE public.email_reminder_subscribers
     SET active = false,
         updated_at = now()
   WHERE unsubscribe_token = p_token;

  GET DIAGNOSTICS v_rows = ROW_COUNT;
  RETURN v_rows > 0;
END;
$fn$;

CREATE OR REPLACE FUNCTION public.set_email_reminder_hour(p_token text, p_hour integer)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $fn$
DECLARE
  v_rows integer;
BEGIN
  IF p_token IS NULL OR length(p_token) <> 48 THEN
    RETURN false;
  END IF;

  IF p_hour IS NULL OR p_hour < 0 OR p_hour > 23 THEN
    RAISE EXCEPTION 'invalid_hour' USING ERRCODE = '22023';
  END IF;

  UPDATE public.email_reminder_subscribers
     SET send_hour = p_hour,
         updated_at = now()
   WHERE unsubscribe_token = p_token;

  GET DIAGNOSTICS v_rows = ROW_COUNT;
  RETURN v_rows > 0;
END;
$fn$;

REVOKE ALL ON FUNCTION public.subscribe_email_reminder(text, integer) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.unsubscribe_email_reminder(text) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.set_email_reminder_hour(text, integer) FROM PUBLIC;

GRANT EXECUTE ON FUNCTION public.subscribe_email_reminder(text, integer) TO anon, authenticated;
GRANT EXECUTE ON FUNCTION public.unsubscribe_email_reminder(text) TO anon, authenticated;
GRANT EXECUTE ON FUNCTION public.set_email_reminder_hour(text, integer) TO anon, authenticated;
